# Home only: links shared before the split (eqsmusica.com/#roster) jump straight to the new page,
# inline in <head> so the home page never flashes first.
LEGACY_REDIRECT = """  <script>
    (function () {
      var routes = %s;
      var target = routes[location.hash];
      if (target) location.replace(target);
    })();
  </script>
"""


def read(rel):
    return (SRC / rel).read_text(encoding="utf-8")


def reroute(html, page_path):
    """Point in-page anchors at their new pages; keep a bare hash when the target is this page."""

    def sub(match):
        href = match.group(1)
        target = ROUTES.get(href)
        if target is None:
            return match.group(0)
        base, _, frag = target.partition("#")
        if base == page_path:
            return f'href="#{frag}"' if frag else 'href="#main"'
        return f'href="{target}"'

    return re.sub(r'href="(#[a-z-]+)"', sub, html)


def root_absolute_assets(html):
    return re.sub(r'(src|href|poster)="(img|video|newsletters)/', r'\1="/\2/', html)


def mark_current(html, page_path):
    """aria-current on the nav/drawer link for this page."""
    if page_path == "/":
        return html
    return re.sub(
        r'(<a class="(?:site-nav__link|mobile-drawer__link)" href="%s")' % re.escape(page_path),
        r'\1 aria-current="page"',
        html,
    )


def promote_heading(section_html):
    """The first section of an interior page owns the page's <h1>."""
    section_html = re.sub(r"<h2(\s[^>]*)?>", lambda m: "<h1%s>" % (m.group(1) or ""), section_html, count=1)
    section_html = re.sub(r"</h2>", "</h1>", section_html, count=1)
    return re.sub(r'<section class="', '<section class="section--page-top ', section_html, count=1)


def featured_artists():
    """Home page strip: the first four roster cards, linking through to the full roster."""
    roster = read("sections/roster.html")
    cards = re.findall(r"\n        <article class=\"artist-card.*?\n        </article>", roster, re.S)
    head, _, _ = roster.partition('<div class="roster__grid')
    head = head.replace('class="roster roster--v4 section reveal" id="roster"',
                        'class="roster roster--v4 roster--featured section reveal" id="featured-artists"')
    head = head.replace(
        '<a class="btn-cta" href="#contact" data-en="Book an Artist" data-es="Reservar Artista">Book an Artist</a>',
        '<a class="btn-cta" href="/artists/" data-en="All Artists →" data-es="Todos los Artistas →">All Artists →</a>',
    )
    cards_html = "".join(cards[:4]).replace('href="#releases"', 'href="/artists/"')
    return (
        head
        + '<div class="roster__grid roster__grid--v4">'
        + cards_html
        + "\n      </div>\n    </div>\n  </section>\n"
    )


def build_page(page):
    path = page["path"]
    body = []
    if "html" in page:
        body.append(page["html"].rstrip("\n"))
    for i, name in enumerate(page.get("sections", [])):
        html = featured_artists() if name == "@featured" else read(f"sections/{name}.html")
        if i == 0 and path != "/":
            html = promote_heading(html)
        body.append(html.rstrip("\n"))

    head = (
        read("partials/head.html")
        .replace("{{TITLE}}", page["title"])
        .replace("{{OG_TITLE}}", page["og_title"])
        .replace("{{DESCRIPTION}}", page["description"])
        .replace("{{PATH}}", path)
    )
    chrome_top = "\n\n".join(read(f"partials/{p}.html").rstrip("\n") for p in ("ticker", "header", "drawer"))
    chrome_bottom = "\n\n".join(read(f"partials/{p}.html").rstrip("\n") for p in ("miniplayer", "actionbar", "footer"))

    if path == "/":
        legacy = {k: v for k, v in ROUTES.items() if k not in ("#top",) and not v.startswith("/#")}
        head = head.replace("</head>", LEGACY_REDIRECT % json.dumps(legacy) + "</head>", 1)

    html = (
        head.replace("<head>", "<head>\n  " + GENERATED_NOTE.strip(), 1)
        + "\n"
        + chrome_top
        + '\n\n<main id="main">\n'
        + "\n\n".join(body)
        + "\n</main>\n\n"
        + chrome_bottom
        + '\n\n<script src="/assets/site.js" defer></script>\n</body>\n</html>\n'
    )
    html = reroute(html, path)
    html = root_absolute_assets(html)
    html = mark_current(html, path)

    if "out" in page:
        out = ROOT / page["out"]
        html = html.replace(f'<link rel="canonical" href="{SITE}{path}">', '<meta name="robots" content="noindex">')
    else:
        out = ROOT / path.strip("/") / "index.html" if path != "/" else ROOT / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    return out.relative_to(ROOT), len(html)


